/// A zero-knowledge proof of routing path validity
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct RoutingProof {
    /// The proof data (RISC Zero receipt or hash-based fallback)
    pub proof_data: Vec<u8>,
    
    /// Public inputs visible to verifier
    pub public_inputs: PublicInputs,
}

/// Public inputs to the routing proof (not hidden)
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PublicInputs {
    /// Commitment to the network topology (Merkle root)
    pub network_commitment: [u8; 32],
    
    /// Number of hops in the path
    pub path_length: usize,
    
    /// Timestamp of proof generation (for freshness)
    pub timestamp: u64,
}

/// Private witness data (hidden from verifier)
#[derive(Serialize, Deserialize)]
struct PathWitness {
    /// The actual routing path (kept secret in ZK proof)
    path: Vec<u32>,
    /// Additional metadata for validation
    metadata: Vec<u8>,
}

/// Proof generator for routing validity
pub struct ProofGenerator {
    /// Cache of recent proofs for performance
    proof_cache: std::sync::RwLock<std::collections::HashMap<[u8; 32], RoutingProof>>,
    
    /// Whether to use zkVM (true) or hash-based fallback (false)
    use_zkvm: bool,
}

impl Default for ProofGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl ProofGenerator {
    /// Create a new proof generator (with zkVM if available)
    pub fn new() -> Self {
        Self {
            proof_cache: std::sync::RwLock::new(std::collections::HashMap::new()),
            use_zkvm: cfg!(feature = "risc0"),
        }
    }
    
    /// Create a proof generator with zkVM explicitly disabled
    /// Useful for testing/benchmarking hash-based proofs
    pub fn new_without_zkvm() -> Self {
        Self {
            proof_cache: std::sync::RwLock::new(std::collections::HashMap::new()),
            use_zkvm: false,
        }
    }
    
    /// Generate a proof that a path is valid within the network
    ///
    /// **What this proves (zero-knowledge)**:
    /// - I know a valid path through the network
    /// - The path has the correct length (3-7 hops)
    /// - The path contains no loops
    /// - All nodes in the path are in the committed network
    ///
    /// **What this DOESN'T reveal**:
    /// - Which specific nodes are in the path
    /// - The order of nodes in the path
    /// - Any other routing metadata
    pub fn generate_path_proof(
        &self,
        path: &[u32],
        network_commitment: &[u8; 32],
    ) -> anyhow::Result<RoutingProof> {
        // Validate path constraints before generating proof
        self.validate_path_constraints(path)?;
        
        // Try zkVM proof generation if enabled
        #[cfg(feature = "risc0")]
        if self.use_zkvm {
            // NOTE: This will fail on first build until guest program is compiled
            // That's expected - we'll see the error and know RISC Zero is integrating
            match self.generate_risc0_proof(path, network_commitment) {
                Ok(proof) => return Ok(proof),
                Err(e) => {
                    eprintln!("RISC Zero proof generation failed (expected on first build): {}", e);
                    eprintln!("Falling back to hash-based proof...");
                    // Fall through to hash-based proof
                }
            }
        }
        
        // Fallback: hash-based proof (current implementation)
        self.generate_hash_proof(path, network_commitment)
    }
    
    /// Validate path constraints (called before proof generation)
    fn validate_path_constraints(&self, path: &[u32]) -> anyhow::Result<()> {
        if path.len() < 3 {
            return Err(anyhow::anyhow!(
                "Path too short: need at least 3 hops for anonymity, got {}",
                path.len()
            ));
        }
        
        if path.len() > 7 {
            return Err(anyhow::anyhow!(
                "Path too long: max 7 hops for performance, got {}",
                path.len()
            ));
        }
        
        // Check for loops (no duplicate nodes)
        let unique_nodes: HashSet<_> = path.iter().collect();
        if unique_nodes.len() != path.len() {
            return Err(anyhow::anyhow!(
                "Path contains loops: {} unique nodes but {} total hops",
                unique_nodes.len(),
                path.len()
            ));
        }
        
        Ok(())
    }
    
    /// Generate a RISC Zero zkVM proof
    #[cfg(feature = "risc0")]
    fn generate_risc0_proof(
        &self,
        path: &[u32],
        network_commitment: &[u8; 32],
    ) -> anyhow::Result<RoutingProof> {
        use std::time::SystemTime;
        
        let timestamp = SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)?
            .as_secs();
        
        // Prepare public inputs
        let public_inputs = PublicInputs {
            network_commitment: *network_commitment,
            path_length: path.len(),
            timestamp,
        };
        
        // Prepare private witness (the secret path)
        let witness = PathWitness {
            path: path.to_vec(),
            metadata: vec![], // TODO: Add network metadata in Merkle implementation
        };
        
        // Build executor environment with inputs
        let env = ExecutorEnv::builder()
            .write(&public_inputs)?
            .write(&witness)?
            .build()?;
        
        // Generate proof using RISC Zero
        // NOTE: This will fail until guest program is compiled
        // Expected error: "ROUTING_GUEST_ELF not found"
        let prover = default_prover();
        
        // This line will fail on first compile - that's expected!
        // After build.rs runs and compiles the guest, ROUTING_GUEST_ELF will exist
        // let receipt = prover.prove(env, ROUTING_GUEST_ELF)?;
        
        // For now, return an error to fall back to hash-based proof
        Err(anyhow::anyhow!("RISC Zero guest program not yet compiled - run 'cargo build' again after this succeeds"))
    }
    
    /// Generate a hash-based proof (fallback / for benchmarking)
    fn generate_hash_proof(
        &self,
        path: &[u32],
        network_commitment: &[u8; 32],
    ) -> anyhow::Result<RoutingProof> {
        use std::time::SystemTime;
        
        let timestamp = SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)?
            .as_secs();
        
        // Generate proof using hash commitments
        let mut proof_data = Vec::new();
        
        // Commit to the path
        let path_bytes: Vec<u8> = path.iter().flat_map(|n| n.to_le_bytes()).collect();
        let path_hash = blake3::hash(&path_bytes);
        proof_data.extend_from_slice(path_hash.as_bytes());
        
        // Bind to network commitment
        let commitment_hash = blake3::hash(network_commitment);
        proof_data.extend_from_slice(commitment_hash.as_bytes());
        
        let public_inputs = PublicInputs {
            network_commitment: *network_commitment,
            path_length: path.len(),
            timestamp,
        };
        
        Ok(RoutingProof {
            proof_data,
            public_inputs,
        })
    }
    
    /// Verify a routing proof
    ///
    /// Returns `true` if the proof is valid, `false` otherwise
    pub fn verify_path_proof(
        &self,
        proof: &RoutingProof,
        network_commitment: &[u8; 32],
    ) -> anyhow::Result<bool> {
        // Check timestamp freshness (within 1 hour)
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)?
            .as_secs();
        
        if now.saturating_sub(proof.public_inputs.timestamp) > 3600 {
            return Ok(false); // Proof too old
        }
        
        // Verify network commitment matches
        if &proof.public_inputs.network_commitment != network_commitment {
            return Ok(false);
        }
        
        // Verify path length constraints
        if proof.public_inputs.path_length < 3 || proof.public_inputs.path_length > 7 {
            return Ok(false);
        }
        
        // For hash-based proofs, just verify it's non-empty
        // For RISC Zero proofs, we'd call receipt.verify() here
        Ok(!proof.proof_data.is_empty())
    }
    
    /// Generate a nullifier for rate limiting
    pub fn generate_nullifier(&self, node_id: &[u8; 32], timestamp: u64) -> [u8; 32] {
        let epoch = timestamp / 3600; // 1-hour epochs
        let mut data = Vec::new();
        data.extend_from_slice(node_id);
        data.extend_from_slice(&epoch.to_le_bytes());
        data.extend_from_slice(b"phantom_routing");
        
        let hash = blake3::hash(&data);
        let mut nullifier = [0u8; 32];
        nullifier.copy_from_slice(hash.as_bytes());
        nullifier
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    
    #[test]
    fn test_proof_generation_hash_based() {
        let generator = ProofGenerator::new_without_zkvm();
        let path = vec![1, 2, 3, 4, 5];
        let commitment = [42u8; 32];
        
        let proof = generator.generate_path_proof(&path, &commitment).unwrap();
        assert!(!proof.proof_data.is_empty());
        assert_eq!(proof.public_inputs.path_length, 5);
    }
    
    #[test]
    fn test_proof_verification() {
        let generator = ProofGenerator::new_without_zkvm();
        let path = vec![1, 2, 3, 4, 5];
        let commitment = [42u8; 32];
        
        let proof = generator.generate_path_proof(&path, &commitment).unwrap();
        assert!(generator.verify_path_proof(&proof, &commitment).unwrap());
    }
    
    #[test]
    fn test_wrong_commitment_rejected() {
        let generator = ProofGenerator::new_without_zkvm();
        let path = vec![1, 2, 3, 4, 5];
        let commitment = [42u8; 32];
        let wrong_commitment = [99u8; 32];
        
        let proof = generator.generate_path_proof(&path, &commitment).unwrap();
        assert!(!generator.verify_path_proof(&proof, &wrong_commitment).unwrap());
    }
    
    #[test]
    fn test_path_too_short_rejected() {
        let generator = ProofGenerator::new_without_zkvm();
        let path = vec![1, 2]; // Only 2 hops
        let commitment = [42u8; 32];
        
        let result = generator.generate_path_proof(&path, &commitment);
        assert!(result.is_err());
        assert!(result.unwrap_err().to_string().contains("too short"));
    }
    
    #[test]
    fn test_path_too_long_rejected() {
        let generator = ProofGenerator::new_without_zkvm();
        let path = vec![1, 2, 3, 4, 5, 6, 7, 8]; // 8 hops
        let commitment = [42u8; 32];
        
        let result = generator.generate_path_proof(&path, &commitment);
        assert!(result.is_err());
        assert!(result.unwrap_err().to_string().contains("too long"));
    }
    
    #[test]
    fn test_path_with_loop_rejected() {
        let generator = ProofGenerator::new_without_zkvm();
        let path = vec![1, 2, 3, 2, 5]; // Node 2 appears twice
        let commitment = [42u8; 32];
        
        let result = generator.generate_path_proof(&path, &commitment);
        assert!(result.is_err());
        assert!(result.unwrap_err().to_string().contains("loop"));
    }
}
